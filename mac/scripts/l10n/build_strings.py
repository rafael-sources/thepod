#!/usr/bin/env python3
"""Generates Resources/en.lproj/Localizable.strings (and InfoPlist.strings: camera/microphone permissions, name) from
l10n/en.xliff (keys) and l10n/en.json (translations).
Checks that the % specifiers match and warns about untranslated keys. --check only reports."""
import re, sys, json, pathlib, xml.etree.ElementTree as ET
root = pathlib.Path(__file__).resolve().parents[2]
ns = {'x': 'urn:oasis:names:tc:xliff:document:1.2'}
files = ET.parse(root/'l10n/en.xliff').getroot().findall('x:file', ns)
is_plist = lambda f: 'InfoPlist' in f.get('original', '')
units = [u for f in files if not is_plist(f) for u in f.findall('.//x:trans-unit', ns)]
plist_units = [u for f in files if is_plist(f) for u in f.findall('.//x:trans-unit', ns)]
keys = []
for u in units:
    s = u.find('x:source', ns).text
    if s and s not in keys: keys.append(s)
tr = json.load(open(root/'l10n/en.json')) if (root/'l10n/en.json').exists() else {}
spec = re.compile(r'%(\d+\$)?[@dlfs.0-9]*[@dfsux]|%lld|%%')
missing, bad, same = [], [], []
out = ['/* thePod in English. Generated by scripts/l10n/build_strings.py from en.xliff + en.json. Do not edit by hand. */']
def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
for k in keys:
    v = tr.get(k)
    if v is None: missing.append(k); continue
    if sorted(spec.findall(k)) != sorted(spec.findall(v)): bad.append((k, v)); continue
    if v.strip() == k.strip() and re.search(r'[a-záéíóúñ]{4,}', k, re.I) and not k.isupper() and k not in ('Studio', 'Reels', 'Reel', 'Master', 'Solo'): same.append(k)
    out.append(f'"{esc(k)}" = "{esc(v)}";')
plist = ['/* thePod in English: Info.plist strings (permission prompts, name). Generated by scripts/l10n/build_strings.py. */']
for u in plist_units:
    k, s = u.get('id'), u.find('x:source', ns).text or ''
    v = tr.get(s)
    if v is None: missing.append(s); continue
    plist.append(f'"{esc(k)}" = "{esc(v)}";')
print(f'{len(keys)} keys · {len(keys) - len(missing) - len(bad)} translated · {len(missing)} untranslated · {len(bad)} with mismatched % · {len(same)} same as Spanish', file=sys.stderr)
for k, v in bad[:20]: print('  % mismatch:', repr(k)[:80], '→', repr(v)[:80], file=sys.stderr)
if '--check' in sys.argv:
    for k in missing[:30]: print('  missing:', repr(k)[:100], file=sys.stderr)
    for k in same[:30]: print('  same:', repr(k)[:100], file=sys.stderr)
    sys.exit(1 if (missing or bad) else 0)
(root/'Sources/Resources/en.lproj/Localizable.strings').write_text('\n'.join(out) + '\n')
(root/'Sources/Resources/en.lproj/InfoPlist.strings').write_text('\n'.join(plist) + '\n')
json.dump(missing, open(root/'l10n/missing.json', 'w'), ensure_ascii=False, indent=0)
